"""Write docs/sw.js: caches every page and asset so the site works offline after one visit."""
import hashlib


def build(DOCS):
    files = sorted(p.relative_to(DOCS).as_posix() for p in DOCS.rglob("*")
                   if p.is_file() and p.name not in ("sw.js", "README.md") and not p.name.startswith("OFL"))
    urls = ["./"] + [f[:-len("index.html")] if f.endswith("index.html") else f for f in files]
    h = hashlib.sha1()
    for f in files:
        h.update((DOCS / f).read_bytes())
    ver = h.hexdigest()[:10]
    lst = ",\n  ".join(f'"{u}"' for u in dict.fromkeys(urls))
    (DOCS / "sw.js").write_text(f"""/* Offline cache for Dīwān al-Wathāʾiq. Generated by tools/service_worker.py. */
var CACHE = "diwan-{ver}";
var FILES = [
  {lst}
];
self.addEventListener("install", function (e) {{
  e.waitUntil(caches.open(CACHE).then(function (c) {{ return c.addAll(FILES); }}).then(function () {{ return self.skipWaiting(); }}));
}});
self.addEventListener("activate", function (e) {{
  e.waitUntil(caches.keys().then(function (ks) {{
    return Promise.all(ks.filter(function (k) {{ return k.indexOf("diwan-") === 0 && k !== CACHE; }}).map(function (k) {{ return caches.delete(k); }}));
  }}).then(function () {{ return self.clients.claim(); }}));
}});
self.addEventListener("fetch", function (e) {{
  var u = new URL(e.request.url);
  if (e.request.method !== "GET" || u.origin !== location.origin) return;   // the n8n board stays live
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then(function (hit) {{
    return hit || fetch(e.request).then(function (res) {{
      if (res.ok) {{ var copy = res.clone(); caches.open(CACHE).then(function (c) {{ c.put(e.request, copy); }}); }}
      return res;
    }}).catch(function () {{ return caches.match("404.html"); }});
  }}));
}});
""", encoding="utf-8")
